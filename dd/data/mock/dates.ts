import type { DateExperience, DateScene, DateStop } from "@/types";
import { photo } from "@/lib/utils";

/** [time, placeName, category, durationMinutes, estimatedCost, description] */
type StopTuple = [string, string, string, number, number, string];

interface DateSeed {
  id: string;
  title: string;
  area: string;
  budgetMin: number;
  budgetMax: number;
  scene: DateScene;
  tags: string[];
  tips: string[];
  rating: number;
  reviewCount: number;
  saveCount: number;
  reproductionCount: number;
  stops: StopTuple[];
}

function mkDate(seed: DateSeed): DateExperience {
  const timeline: DateStop[] = seed.stops.map(
    ([time, placeName, category, durationMinutes, estimatedCost, description], i) => ({
      id: `${seed.id}-s${i + 1}`,
      order: i + 1,
      time,
      placeName,
      area: seed.area,
      category,
      durationMinutes,
      estimatedCost,
      description,
      image: photo(`${seed.id}-s${i + 1}`, 640, 480),
    })
  );
  return {
    id: seed.id,
    // Convention: date dNN is linked from post pNN (see data/mock/posts.ts)
    postId: `p${seed.id.slice(1)}`,
    title: seed.title,
    area: seed.area,
    budgetMin: seed.budgetMin,
    budgetMax: seed.budgetMax,
    durationMinutes: timeline.reduce((sum, s) => sum + s.durationMinutes, 0),
    scene: seed.scene,
    tags: seed.tags,
    timeline,
    tips: seed.tips,
    rating: seed.rating,
    reviewCount: seed.reviewCount,
    saveCount: seed.saveCount,
    reproductionCount: seed.reproductionCount,
  };
}

