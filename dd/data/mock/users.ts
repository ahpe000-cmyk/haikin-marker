import type { User } from "@/types";
import { avatarPhoto } from "@/lib/utils";
import { calcCreatorScore } from "@/lib/score";

interface UserSeed {
  id: string;
  username: string;
  displayName: string;
  bio: string;
  location: string;
  specialty?: string;
  followers: number;
  following: number;
  postCount: number;
  dateCount: number;
  totalSavesGenerated: number;
  totalReproductions: number;
  averageRating: number;
}

function mkUser(seed: UserSeed): User {
  return {
    ...seed,
    type: "individual",
    accountType: "individual",
    avatar: avatarPhoto(seed.id),
    ddScore: calcCreatorScore({
      totalReproductions: seed.totalReproductions,
      totalSavesGenerated: seed.totalSavesGenerated,
      averageRating: seed.averageRating,
      // Demo engagement proxy: followers count (see lib/score.ts note)
      engagement: seed.followers,
      postCount: seed.postCount,
    }),
  };
}

